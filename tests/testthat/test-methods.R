test_that("coef, impute, fitted, residuals, predict and plots", {
  sim <- small_sim()
  fit <- jcglasso(data = sim$Z, nrho = 2, nlambda = 2, rho.min.ratio = 0.3, lambda.min.ratio = 0.3, nu = 0.1)
  B <- coef(fit, "B", lambda.id = 2, rho.id = 2)
  expect_equal(dim(B), c(4L, 6L, 2L))
  Sg <- coef(fit, "Sigma", class.id = 1, lambda.id = 2, rho.id = 2)
  expect_equal(Sg %*% fit$Tht[, , 1, 2, 2], diag(6), tolerance = 1e-8, ignore_attr = TRUE)
  Zi <- impute(fit, lambda.id = 2, rho.id = 2)
  expect_false(anyNA(Zi$class1))
  obs <- event(sim$Z)$class1 == 0
  expect_equal(Zi$class1[obs], cbind(sim$Z$Y$class1, sim$Z$X$class1)[obs])
  r <- residuals(fit, lambda.id = 2, rho.id = 2); fv <- fitted(fit, lambda.id = 2, rho.id = 2)
  expect_equal(r$class1 + fv$class1, Zi$class1[, 1:6], ignore_attr = TRUE)
  pr <- predict(fit, newdata = list(matrix(0, 1, 3), matrix(0, 1, 3)), lambda.id = 2, rho.id = 2)
  expect_equal(unname(pr$class1[1, ]), unname(B[1, , 1]))
  expect_error(fitted(fit), "lambda.id")
  pdf(NULL); on.exit(dev.off())
  expect_silent(plot(fit))
  expect_silent(plot(fit, "B"))
  expect_silent(plot(select_jcglasso(fit, GoF = BIC)))
  expect_silent(plot(BIC(fit)))
})

test_that("graphs", {
  skip_if_not_installed("igraph")
  sim <- small_sim()
  fit <- jcglasso(data = sim$Z, nrho = 2, nlambda = 2, rho.min.ratio = 0.3, lambda.min.ratio = 0.3, nu = 0.1)
  g <- to_graph(fit, lambda.id = 2, rho.id = 2)
  expect_s3_class(g, "jcglasso2igraph")
  expect_equal(igraph::ecount(g$Gyy$class1), fit$dfTht[1, 2, 2])
  expect_equal(igraph::ecount(g$Gxy$class1), fit$dfB[1, 2, 2])
  expect_length(getGraph(g, "bipartite"), 2L)
})

test_that("comparison with cglasso for K = 1 without predictors", {
  skip_if_not_installed("cglasso")
  set.seed(5)
  Y <- matrix(rnorm(80 * 5), 80) %*% chol(0.5^abs(outer(1:5, 1:5, "-")))
  colnames(Y) <- paste0("Y", 1:5)
  f1 <- jcglasso(data = datajcggm(Y), rho = 0.1, thr.em = 1e-8, thr.bcd = 1e-9)
  f2 <- cglasso::cglasso(. ~ ., data = cglasso::datacggm(Y), rho = 0.1, thr.em = 1e-8, thr.bcd = 1e-9)
  expect_equal(unname(f1$Tht[, , 1, 1, 1]), unname(f2$Tht[, , 1, 1]), tolerance = 1e-4)
})
