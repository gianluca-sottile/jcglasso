test_that("QFun, information criteria and selection", {
  sim <- small_sim()
  fit <- jcglasso(data = sim$Z, nrho = 3, nlambda = 3, rho.min.ratio = 0.3, lambda.min.ratio = 0.3, nu = 0.1)
  Q <- QFun(fit)
  expect_s3_class(Q, "QFun")
  b <- BIC(fit); a <- AIC(fit)
  expect_equal(dim(b$value_gof), c(3L, 3L))
  expect_equal(sum(-2 * Q$value + log(fit$nobs) * Q$df) , sum(b$value_gof))
  expect_true(all(b$value_gof - a$value_gof >= 0))
  best <- select_jcglasso(fit, GoF = b)
  i <- which(b$value_gof == min(b$value_gof), arr.ind = TRUE)[1, ]
  expect_equal(best$lambda, fit$lambda[i[1]]); expect_equal(best$rho, fit$rho[i[2]])
  expect_equal(select_jcglasso(fit, lambda.id = 2, rho.id = 3)$rho, fit$rho[3])
  Qj <- QFun(fit, part = "joint")
  expect_true(all(Qj$df > Q$df))
  expect_output(print(b), "minimum")
  expect_output(summary(fit, GoF = BIC), "BIC")
})

test_that("jcggm keeps the support and solves the unpenalized problem", {
  sim <- small_sim()
  fit <- jcglasso(data = sim$Z, nrho = 2, nlambda = 2, rho.min.ratio = 0.3, lambda.min.ratio = 0.3, nu = 0.1)
  m <- jcggm(fit, lambda.id = 2, rho.id = 2)
  expect_s3_class(m, "jcggm")
  expect_equal(m$B[-1, , , 1, 1] != 0, fit$B[-1, , , 2, 2] != 0)
  expect_equal(m$Tht[, , , 1, 1] != 0, fit$Tht[, , , 2, 2] != 0)
  expect_lt(max(kkt(m)), 1e-3)
  Qm <- QFun(fit, mle = TRUE)
  expect_true(all(Qm$value[, 2, 2] >= QFun(fit)$value[, 2, 2] - 1e-6))
})
